-- Add stock snapshots table for storing comprehensive stock analysis
-- This table stores AI-generated analysis snapshots for securities

SET search_path TO overlord, public;

CREATE TABLE IF NOT EXISTS stock_snapshots (
    id SERIAL PRIMARY KEY,
    ticker VARCHAR(50) NOT NULL,
    company_name VARCHAR(255),
    snapshot_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    analysis_data JSONB NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Create index for faster ticker lookups
CREATE INDEX IF NOT EXISTS idx_stock_snapshots_ticker ON stock_snapshots(ticker);

-- Create index for sorting by snapshot date
CREATE INDEX IF NOT EXISTS idx_stock_snapshots_date ON stock_snapshots(snapshot_date DESC);

-- Create composite index for finding the most recent snapshot for a ticker
CREATE INDEX IF NOT EXISTS idx_stock_snapshots_ticker_date ON stock_snapshots(ticker, snapshot_date DESC);

-- Create index on JSONB for querying specific fields within the analysis
CREATE INDEX IF NOT EXISTS idx_stock_snapshots_analysis ON stock_snapshots USING GIN (analysis_data);

-- Add trigger to update updated_at timestamp
CREATE TRIGGER update_stock_snapshots_updated_at
    BEFORE UPDATE ON stock_snapshots
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

-- Add comment to table
COMMENT ON TABLE stock_snapshots IS 'Stores comprehensive stock analysis snapshots generated by AI';
COMMENT ON COLUMN stock_snapshots.ticker IS 'Stock ticker symbol (e.g., AAPL, MSFT)';
COMMENT ON COLUMN stock_snapshots.company_name IS 'Full company name';
COMMENT ON COLUMN stock_snapshots.snapshot_date IS 'When this snapshot was generated';
COMMENT ON COLUMN stock_snapshots.analysis_data IS 'JSONB containing the complete StockAnalysis data structure';
